ADVANCE = 5.5  # grid units from one character to the next


def text_strokes(
    text: str, x: float, y: float, height: float, anchor: str = "middle"
) -> list[list[tuple[float, float]]]:
    """Strokes for `text` in board millimetres, baseline at y, `height` mm tall."""
    scale = height / 6
    width = (len(text) * ADVANCE - (ADVANCE - 4)) * scale
    x0 = {"start": x, "middle": x - width / 2, "end": x - width}[anchor]
    strokes = []
    for i, char in enumerate(text.upper()):
        glyph = GLYPHS.get(char, GLYPHS["-"])
        ox = x0 + i * ADVANCE * scale
        for line in glyph:
            strokes.append([(ox + gx * scale, y + gy * scale) for gx, gy in line])
    return strokes
